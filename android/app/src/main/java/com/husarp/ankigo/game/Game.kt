package com.husarp.ankigo.game

import java.time.Instant
import java.time.LocalDate
import java.time.ZoneId
import java.time.format.DateTimeParseException
import kotlin.random.Random

// TICKET T11 owns this file. Public signatures are fixed (the UI calls them); add private helpers freely.

private const val RELEASED_KEPT = 5_000 // how many released Ankimon ids the game remembers (GameState.releasedAnkimon)

/**
 * The game controller: turns AnkiDroid answers into Ankimon rounds and between-battle actions into state changes.
 * Single-threaded: call everything on the main thread; the caller saves after each call (GameRepo does).
 */
class Game(val data: GameData, val state: GameState, val rng: Random = Random.Default, val clock: () -> Long = { System.currentTimeMillis() }) {

    init { PokeDoll.migrate(state) }

    // Reveal before any screen reads the save; keep its alerts for the battle host, not a widget tick.
    private val loadEvents = mutableListOf<GameEvent>().also { events ->
        state.mons.filter { Bond.level(it.bondPoints) >= 3 }.forEach { MatchupKnowledge.reveal(data, state, it, events) }
    }

    /** Game day key "yyyy-MM-dd" for [now]; a day starts at settings.dayStartHour (phone time zone). */
    fun dayKey(now: Long = clock()): String =
        Instant.ofEpochMilli(now).atZone(ZoneId.systemDefault())
            .minusHours(state.settings.dayStartHour.coerceIn(0, 23).toLong()).toLocalDate().toString()

    /** Day rollover if the day changed (daily counters, goal streak, shop). Safe to call often. */
    fun tick(): List<GameEvent> {
        val today = dayKey()
        if (state.day == today) return emptyList()
        val firstEver = state.day.isEmpty()
        state.day = today
        if (firstEver) return emptyList()
        state.reviewsToday = 0
        state.cashToday = 0
        state.cashFracNum = 0; state.cashFracDen = 1
        state.buttonsToday.fill(0)
        // An undo whose redo never came must not swallow a real answer days later.
        state.redo.clear()
        Shop.ensureToday(data, state)
        refreshNext() // the daily goal count restarted: the predicted next one changes with it
        return listOf(GameEvent.DayChanged(today)) + StreakFreeze.rollover(state, today)
    }

    /** Answers per battle round: always [Tuning.CARDS_PER_ROUND]; tests lower it to shorten fights. */
    internal var roundAnswers: Int = Tuning.CARDS_PER_ROUND

    /** Same battle rules; only the rewards generated by this local answer are reduced. */
    fun onPracticeAnswer(a: Answer): List<GameEvent> {
        check(!state.practiceRewards)
        state.practiceRewards = true
        return try { onAnswer(a) } finally { state.practiceRewards = false }
    }

    /**
     * One answer from AnkiDroid -> bookkeeping + (every cardsPerRound answers) one battle round. PLAN 206: a switch queued while this
     * card showed ([requestMain]) comes in right after the answer's own events, in the same list. It is applied AFTER the answer was
     * counted for the stats and achievements: the switch counts its own wild attack (switchHit), so nothing is counted twice. An
     * Ignored answer (the redo after an undo) has no Counted event and applies nothing; the queue is cleared before it is applied.
     */
    fun onAnswer(a: Answer): List<GameEvent> {
        val events = answer(a).toMutableList()
        StudyStats.record(state, events)
        Achievements.settle(data, state, clock(), events, answerAt = a.at) // R4-03: counts these events once (an Ignored answer has none), then adds AchievementReached
        if (events.any { it is GameEvent.Counted }) events += applyQueuedMain()
        return events
    }

    /**
     * PLAN 206: the queued switch comes in now (today's [setMain] path: MainChanged, and the wild one's free hit when [switchCostsAHit]). A queue gone stale (left the team, already the main) is dropped.
     * R19-T (PLAN 288): the switch takes none of the round's answers and marks no dot; the hit comes on top of the normal flow.
     */
    private fun applyQueuedMain(): List<GameEvent> {
        val uid = state.pendingMain ?: return emptyList()
        switchBlocker()?.let {
            state.pendingMain = null; state.pendingTeam = null; state.pendingCycle = false
            return listOf(GameEvent.Info(it))
        }
        val team = state.pendingTeam
        state.pendingTeam = null
        val cycle = state.pendingCycle
        state.pendingMain = null; state.pendingCycle = false // first: whatever happens below, the switch is never applied twice
        if (team != null && team.firstOrNull() == uid && team.all { state.mon(it) != null }) {
            val old = state.team.firstOrNull()
            state.team.clear(); state.team.addAll(team)
            return changed("${state.main?.name} is your main now.", old).events.map { if (it is GameEvent.MainChanged) it.copy(queued = true) else it }
        }
        if (state.mon(uid) == null || uid !in state.team || state.team.firstOrNull() == uid) return emptyList()
        // a queued [cycleMain] keeps its rotation of the first three ([A,B,C] -> [B,C,A]) while the one it queued is still next in line
        val events = if (cycle && state.team.getOrNull(1) == uid) rotateMain().events else setMain(uid).events
        return events.map { if (it is GameEvent.MainChanged) it.copy(queued = true) else it } // R18-B: marks the switch as a queued one (R19-T: the Study dots no longer use it)
    }

    private fun answer(a: Answer): List<GameEvent> {
        val events = tick().toMutableList()

        // A local answer cannot be the redo of an Anki scheduling write.
        val pending = if (state.practiceRewards) 0 else state.redo[a.cardId] ?: 0
        if (pending > 0) {
            if (pending == 1) state.redo.remove(a.cardId) else state.redo[a.cardId] = pending - 1
            events += GameEvent.Ignored("Answer repeated after an undo")
            return events
        }

        val main = state.main ?: return events // no starter yet: nothing to count

        val button = a.button.coerceIn(0, 4)
        val points = Tuning.POINTS[button]
        state.reviewsToday++
        state.totalReviews++
        state.buttonsToday[button]++
        if (!a.neutral) state.cardStreak = if (button == 1) 0 else state.cardStreak + 1   // PLAN 155: the OK of a new card neither breaks nor builds the combo
        if (state.cardStreak > state.bestCardStreak) state.bestCardStreak = state.cardStreak
        events += GameEvent.Counted(button, points, state.reviewsToday, state.cardStreak, a.catchUp, a.neutral)
        Healing.restBench(data, state) // every counted answer (catch-up ones too): the bench heals 0.5 % of max HP, exactly

        // Daily goal: once a day, the first time the count reaches it (also if the goal was lowered during the day).
        if (state.reviewsToday >= DailyGoal.today(state) && state.lastGoalDay != state.day) {
            val streakBefore = if ((state.streakThroughDay ?: state.lastGoalDay) == previousDay(state.day)) state.streakDays else 0 // goal days in a row before today
            state.streakDays = streakBefore + 1
            state.lastGoalDay = state.day
            state.streakThroughDay = state.day
            state.bestStreakDays = maxOf(state.bestStreakDays, state.streakDays)
            events += GameEvent.Info("Daily goal reached!")
            DailyGift.give(data, state, events) // R14-B2-D: once a day, this moment never repeats on a day (lastGoalDay is saved): one gift into the Bag, no money
        }

        Economy.onReview(data, state, rng, events)
        Badges.onReviews(state, events, clock())

        events += ensureEncounter()
        val battle = state.battle ?: return events
        if (main.hp > 0 && battle.wild.hp > 0) Bond.add(data, state, main, Bond.CARD_POINTS, events, state.activeHeldItem(main) == "soothe-bell", studyAnswer = !state.practiceRewards)
        // R10-B22: who attacks depends on each answer, not on the point sum. A battle saved before keeps only the sum: restore the buttons from it.
        if (battle.buttons.size != battle.answers) { battle.buttons.clear(); battle.buttons += RoundRule.restore(battle.answers, battle.tally) }
        // R19-T (PLAN 284): the OK of a new card (PLAN 155) is one of the round's answers, a neutral move: it fills a dot and counts toward the
        // round, but has no points and no power ([RoundRule] skips it). It was counted above (reviews, money, goal, stats), the combo is untouched.
        battle.tally += if (a.neutral) 0 else points
        battle.buttons += if (a.neutral) Tuning.BUTTON_OK else button
        battle.answers++
        if (RoundRule.answerBoost(battle, battle.buttons.last())) {
            events += BattleEngine.weaknessBoost(data, battle, main, rng, state.settings.moveChoice)
        }
        val n = roundAnswers
        if (battle.answers < n) {
            events += GameEvent.Charge(battle.tally, battle.answers, n)
            refreshNext()
            return events
        }

        val forceStrongest = RoundRule.strongestRound(battle, battle.buttons.takeLast(n))
        val plan = RoundRule.plan(battle.buttons.takeLast(n))
        events += GameEvent.RoundStart(plan.multiplier, battle.tally, plan.enemyActs, plan.mainActs, plan.enemyPower)
        battle.tally = 0
        battle.answers = 0
        battle.buttons.clear()
        battle.team = state.team.mapNotNull { state.mon(it) } // R17C-4: Beat Up hits once for each team member with HP
        events += BattleEngine.playRound(data, battle, main, plan.multiplier, plan.enemyActs, rng, plan.enemyPower, plan.mainActs, state.settings.moveChoice, forceStrongest)
        settleFight(battle, main, events)
        return events
    }

    /**
     * What follows an action of the fight (a round, or the free hit of a switch): a wild one that fainted is caught or defeated,
     * a Main that fainted is healed at once and the wild one is lost (Ankimon), then the next encounter starts if the fight is over.
     */
    private fun settleFight(battle: Battle, main: Mon, events: MutableList<GameEvent>) {
        MatchupKnowledge.observe(data, state, battle, main, events)
        if (battle.field.player[RemainingMoves.ESCAPED] == 1) {
            state.battle = null
            events += ensureEncounter()
            refreshNext()
            return
        }
        if (battle.wild.hp <= 0) {
            resolveWild(battle, main, events)
            state.battle = null
        }
        if (main.hp <= 0) {
            // Ankimon: a fainted main is healed at once and the wild one is lost.
            main.hp = StatCalc.maxHp(data, main)
            events += GameEvent.MainHealed(main.uid, main.name, main.hp)
            state.battle = null
        }
        events += ensureEncounter() // no-op while a fight is still going
        refreshNext()
    }

    /**
     * The wild one fainted: catch or defeat it by the auto rule (decide() honours a one-off override). Both count as a win (defeat
     * counters, trainer XP) and give the same Pokémon XP and the same win money (R13 Part C, Economy.onWin, on the day's curve).
     */
    private fun resolveWild(battle: Battle, main: Mon, events: MutableList<GameEvent>) {
        AbilityAdaptations.onWin(state, rng, events)
        val now = clock()
        PokeDoll.won(state, now)
        AchievementPokemon.record(state, "defeats", main, data)
        if (main.hp > 0 && main.hp * 100 < StatCalc.maxHp(data, main) * Achievements.COMEBACK_PERCENT)
            AchievementPokemon.record(state, "comebacks", main, data)
        SecretAchievements.win(state, battle, main)
        val bondLevel = Bond.level(main.bondPoints)
        val plan = Catching.plan(data, state, battle)
        when (plan.outcome) {
            Outcome.CATCH -> {
                val caught = Catching.addToCollection(data, state, battle.wild, battle.tier, null, now, events)
                state.ballCatches.merge("auto", 1, Int::plus)
                plan.duplicate?.let { swapDuplicate(it, battle.wild, caught, events) }
                if (Tuning.CATCH_GIVES_XP) Progression.rewardCatch(data, state, main, battle.wild, now, rng, events)
                Healing.healMain(data, main, HealReason.CATCH, events) // after the rewards
                // A catch is a win like a defeat: defeat counters + trainer XP by tier.
                main.defeats++
                state.defeats++
                state.catchWins++
                Trainer.addDefeatXp(state, battle.tier, events)
                Economy.onWin(state, events, bondLevel, rng)
            }
            Outcome.DEFEAT -> {
                state.defeatedSpecies += battle.wild.species
                Progression.rewardDefeat(data, state, main, battle.wild, now, rng, events)
                Healing.healMain(data, main, HealReason.DEFEAT, events) // after XP, level-ups and evolution
                Trainer.addDefeatXp(state, battle.tier, events)
                state.defeats++
                Economy.onWin(state, events, bondLevel, rng)
                plan.duplicate?.let { events += GameEvent.Duplicate(battle.wild.name, battle.wild.level, it.bestLevel, DuplicateResult.DEFEATED) }
                if (plan.ask != null) askToCatch(battle, now, events) // R19-P (PLAN 281): paid as a defeat; "Catch / Catch and replace / Don't catch" waits
            }
        }
    }

    /**
     * R19-P (PLAN 281): "Ask me" met a better copy of a species you own. The fight is over and paid (the Defeated event, XP, coins), the wild
     * Pokémon itself is kept in [GameState.asks] until [answerCatch]; the Defeated event says so ([GameEvent.Defeated.ask]) for the screens.
     */
    private fun askToCatch(battle: Battle, now: Long, events: MutableList<GameEvent>) {
        enqueueAsk(PendingAsk(PendingAsk.Kind.CATCH, battle.wild.uid, battle.wild, battle.tier, at = now))
        val i = events.indexOfLast { it is GameEvent.Defeated }
        if (i >= 0) events[i] = (events[i] as GameEvent.Defeated).copy(ask = true)
    }

    /** Adds [ask] to the waiting questions (one per kind and Pokémon), oldest dropped beyond [AskMe.MAX_WAITING]. */
    private fun enqueueAsk(ask: PendingAsk) {
        state.asks.removeAll { it.kind == ask.kind && it.uid == ask.uid }
        state.asks += ask
        while (state.asks.size > AskMe.MAX_WAITING) state.asks.removeAt(0)
    }

    /**
     * R19-P (PLAN 281): the player's answer to the catch question [uid] (a [PendingAsk.Kind.CATCH]). Answered exactly once: the question is
     * taken out FIRST, a second answer (a second screen, a double tap) finds nothing and changes nothing (not ok).
     *  - DONT: nothing is added; the fight stays a defeat (it was paid already).
     *  - CATCH: the wild Pokémon joins the Box with its own level, IVs, nature, moves... (as an auto catch); both copies stay. The win was
     *    counted at the fight's end, so the catch only adds the catch counters ([GameState.catchWins] keeps "battles won" right).
     *  - REPLACE: CATCH, then the copy it beat ([AskMe.better] looked at NOW: not better any more = both are kept; a shiny or protected copy
     *    is never released) goes. A copy that holds a place (Team / favourite / Exp. Share) is not released here: a release question
     *    ([PendingAsk.Kind.REPLACE], the 2B window) follows; a plain copy goes at once.
     * The result carries the other events (badges, achievements, a main that changed) but no Caught event: the fight's events were played.
     */
    fun answerCatch(uid: String, choice: AskChoice): ActionResult {
        val ask = state.asks.firstOrNull { it.kind == PendingAsk.Kind.CATCH && it.uid == uid } ?: return ActionResult(false, NOTHING_WAITING)
        state.asks.remove(ask)
        val wild = ask.wild ?: return ActionResult(false, NOTHING_WAITING)
        if (choice == AskChoice.DONT) return ActionResult(true, "${wild.name} was not caught.")
        val now = clock()
        val better = if (choice == AskChoice.REPLACE) AskMe.better(state, wild) else null
        val events = mutableListOf<GameEvent>()
        val caught = Catching.addToCollection(data, state, wild, ask.tier, null, now, events)
        state.ballCatches.merge("auto", 1, Int::plus)
        state.catchWins++ // the win itself (defeats) was counted when the fight ended
        StudyStats.addLateCatch(state, caught.shiny)
        Achievements.settle(data, state, now, events)
        var text = "${wild.name} (Lv ${wild.level}) was caught."
        val old = better?.yours?.takeIf { it.uid != caught.uid && AskMe.canReplace(data, state, it) }
        if (old != null) {
            if (AskMe.needsWindow(data, state, old)) enqueueAsk(PendingAsk(PendingAsk.Kind.REPLACE, caught.uid, oldUid = old.uid, at = now))
            else {
                val moved = swapCopies(caught, old, keepPlace = true)
                events += moved.events
                text = "${wild.name} (Lv ${wild.level}) was caught; your Lv ${old.level} one was released."
            }
        }
        return ActionResult(true, text, events.filter { it !is GameEvent.Caught })
    }

    /**
     * R19-P (PLAN 281): the answer to a release question ([PendingAsk.Kind.REPLACE]) for the better copy [newUid]: [release] = release the
     * old one (No / closing the window: false, both stay). With [keepPlace] the new one takes the old one's Team slot, favourite heart and
     * Exp. Share, without it the old one's place goes with it (a team is never left empty: the new one takes the last slot then). The old
     * one's held item goes to the Bag like in any release. Exactly once, like [answerCatch]; a Pokémon that changed meanwhile releases
     * nothing ([Duplicates.CHANGED_NOTHING]). R19-FIX (CX-1): the pair is checked again here ([AskMe.stillReplaces]): an old copy that
     * evolved, got a shiny / protected mark or is no longer worse than the new one is kept, with [AskMe.STALE] as the answer.
     */
    fun answerReplace(newUid: String, release: Boolean, keepPlace: Boolean): ActionResult {
        val ask = state.asks.firstOrNull { it.kind == PendingAsk.Kind.REPLACE && it.uid == newUid } ?: return ActionResult(false, NOTHING_WAITING)
        state.asks.remove(ask)
        if (!release) return ActionResult(true, "Kept both.")
        val new = state.mon(ask.uid)
        val old = ask.oldUid?.let { state.mon(it) }
        if (new == null || old == null || new.uid == old.uid) return ActionResult(false, Duplicates.CHANGED_NOTHING)
        if (!AskMe.stillReplaces(data, state, new, old)) return ActionResult(false, AskMe.STALE)
        return swapCopies(new, old, keepPlace).let { it.copy(message = "${old.shownName} (Lv ${old.level}) was released; ${new.shownName} (Lv ${new.level}) took over.") }
    }

    /** The waiting question to show first ([AskMe.next]); null = none. */
    fun nextAsk(): PendingAsk? = AskMe.next(state)

    /** The text of a second answer to a question that is gone. */
    private val NOTHING_WAITING get() = "Nothing is waiting for an answer."

    /**
     * Releases [old] and puts [new] in its place (R19-P). The release is [release]'s: the held item goes to the Bag and the ID is remembered for imports.
     * [keepPlace]: the Team slot (the main too), the favourite heart and the Exp. Share go to [new]; else they go with [old]
     * and a team left empty takes [new]. A changed main is the usual team change ([changed]) but costs no wild hit: nothing was switched
     * out, a better copy came in.
     */
    private fun swapCopies(new: Mon, old: Mon, keepPlace: Boolean): ActionResult {
        val oldMain = state.team.firstOrNull()
        val oldMainMon = state.main
        val slot = state.team.indexOf(old.uid)
        val shared = state.settings.xpShareUid == old.uid
        old.heldItem?.let { Economy.give(state, it) }
        old.heldItem = null
        if (keepPlace) {
            if (slot >= 0) {
                state.team[slot] = new.uid
                // R19-FIX (CX-2): the new copy may be in the Team already (added while the question waited): one entry only, the old slot's
                val twin = state.team.indices.firstOrNull { it != slot && state.team[it] == new.uid }
                if (twin != null) state.team.removeAt(twin)
            }
            if (old.favourite) new.favourite = true
            if (shared) state.settings.xpShareUid = new.uid
        } else {
            state.team.remove(old.uid)
            if (shared) state.settings.xpShareUid = null
            if (state.team.isEmpty()) state.team += new.uid
        }
        state.mons.remove(old)
        rememberReleased(old.ankimonId ?: old.uid)
        return changed("${old.name} was released.", oldMain, oldMainMon, free = true)
    }

    /**
     * Auto-release duplicates, after the wild one was caught: lets the replaced copy go like a manual release, or keeps both
     * when it may not go. The copy is checked again here; it is never in the team.
     */
    private fun swapDuplicate(dup: Duplicates.Verdict, wild: Mon, caught: Mon, events: MutableList<GameEvent>) {
        val old = dup.release?.takeIf { it in state.mons && Duplicates.keepReason(data, state, it) == null }
        if (old == null) {
            // R19-P (PLAN 281): a best copy that only holds a place (Team / favourite / Exp. Share) is not dropped silently or kept silently:
            // both are kept for now and "Release the old one?" waits for the answer ([answerReplace])
            val holder = dup.best?.takeIf { it in state.mons && AskMe.needsWindow(data, state, it) }
            if (holder != null) enqueueAsk(PendingAsk(PendingAsk.Kind.REPLACE, caught.uid, oldUid = holder.uid, at = clock()))
            events += GameEvent.Duplicate(wild.name, wild.level, dup.bestLevel, DuplicateResult.KEPT_BOTH,
                keptBecause = (dup.kept ?: dup.release?.let { Duplicates.keepReason(data, state, it) })?.label, ask = holder != null)
            return
        }
        state.mons.remove(old)
        rememberReleased(old.ankimonId ?: old.uid)
        events += GameEvent.Duplicate(wild.name, wild.level, old.level, DuplicateResult.SWAPPED, releasedName = old.shownName)
    }

    /** AnkiDroid undo of [count] answers on [cardId]: the battle doesn't rewind; the redo isn't counted again. */
    fun onUndo(cardId: Long, count: Int) {
        if (count <= 0) return
        state.redo[cardId] = (state.redo[cardId] ?: 0) + count
    }

    /** Starts a wild encounter if there is none (and a main exists). */
    fun ensureEncounter(): List<GameEvent> {
        val events = loadEvents.toList()
        loadEvents.clear()
        if (state.battle != null) return events
        val main = state.main ?: return events
        val now = clock()
        // Ankimon rolls the wild one when it appears, with that moment's state; the seed only fixes the random draws.
        val encounterSeed = state.nextSeed
        val r = encounterSeed?.let { Random(it) } ?: rng
        val level = Encounters.wildLevel(main.level, r)
        val roll = Encounters.roll(data, state, level, r)

        val wild = Encounters.makeWild(data, roll, level, rng, now)
        val newSpecies = roll.species !in state.caught
        state.markSeen(roll.species, now)
        val fullHp = StatCalc.maxHp(data, wild)
        val encounterHp = Tuning.wildHp(fullHp, main.level, state.settings.fasterStart)
        wild.hp = encounterHp
        state.battle = Battle(wild, roll.tier, startedAt = now, wildMaxHp = encounterHp.takeIf { it != fullHp }).also { it.encounterSeed = encounterSeed }

        // Seed of the one after this; the prediction (widget silhouette, sprite prefetch) follows the current state.
        state.nextSeed = rng.nextLong()
        refreshNext()

        return events + listOf(
            GameEvent.Encounter(
                wild.species, wild.name, wild.level, wild.shiny, roll.tier,
                wild.hp, encounterHp, willCatch(), newSpecies, wild.uid,
            ),
        )
    }

    /** PLAN 388: only a result's unseen, untouched encounter may be picked again for a changed Main. */
    fun reselectHeldEncounter(wildUid: String): List<GameEvent> {
        val b = state.battle ?: return emptyList()
        if (state.main == null) return emptyList()
        if (b.wild.uid != wildUid || b.rounds != 0 || b.answers != 0 || b.failedThrows != 0 || b.buttons.isNotEmpty()) return emptyList()
        val followingSeed = state.nextSeed
        state.nextSeed = b.encounterSeed ?: followingSeed
        state.battle = null
        val events = ensureEncounter()
        state.nextSeed = followingSeed
        refreshNext()
        return events
    }

    /**
     * Prediction of the next encounter (nextSpecies/Tier/Shiny): the same level and roll a fight starting now would get from
     * [GameState.nextSeed]. Only a preview; the real roll happens when the encounter appears (ensureEncounter).
     */
    private fun refreshNext() {
        val seed = state.nextSeed ?: return
        val main = state.main ?: return
        val r = Random(seed)
        val upcoming = Encounters.roll(data, state, Encounters.wildLevel(main.level, r), r)
        state.nextSpecies = upcoming.species
        state.nextTier = upcoming.tier
        state.nextShiny = upcoming.shiny
    }

    /** What the auto rule will do when the current wild one faints (for the "NEW · will catch" tag). */
    fun willCatch(): Boolean = state.battle?.let { Catching.decide(data, state, it) == Outcome.CATCH } ?: false

    /** Optional tap: one-off catch/defeat choice for this fight (null = back to the auto rule). */
    fun setOverride(o: Outcome?) { state.battle?.override = o }

    /**
     * Optional tap: throw a ball at the current wild Pokémon (AnkiGo fix: success really catches). PLAN 171: the ball is used up either
     * way, and a miss ends the fight: the wild one breaks free and runs away (no XP, no win counted) and the next one comes, as after
     * a defeat. PLAN 170: a ball catch gives the same Pokémon XP as a defeat or an auto catch, and (R13 Part C) the same win money.
     */
    fun throwBall(ball: String, special: String? = null): List<GameEvent> {
        val battle = state.battle ?: return emptyList()
        if (battle.wild.hp <= 0 || ball !in Tuning.BALL_CHANCE || state.count(ball) <= 0) return emptyList()
        if (special != null && (special !in Tuning.OLD_BALLS || state.count(special) <= 0)) return emptyList()
        Economy.take(state, ball)
        if (special != null) Economy.take(state, special)
        val chance = Catching.ballChance(ball, special, data, state, battle, clock())
        val success = rng.nextInt(100) < chance
        val events = mutableListOf<GameEvent>(GameEvent.BallThrow(ball, chance, success, state.count(ball), battle.failedThrows + 1, special)) // the fight itself counts its throws (saved with it)
        if (success) {
            val bondLevel = Bond.level(state.main?.bondPoints ?: 0)
            state.main?.let {
                AchievementPokemon.record(state, "defeats", it, data)
                if (it.hp > 0 && it.hp * 100 < StatCalc.maxHp(data, it) * Achievements.COMEBACK_PERCENT)
                    AchievementPokemon.record(state, "comebacks", it, data)
                SecretAchievements.win(state, battle, it)
            }
            if (ball == "poke-ball" && battle.failedThrows == 0 && battle.wild.hp == battle.maxWildHp(data)) Achievements.bump(state, Metric.PERFECT_THROW)
            AbilityAdaptations.onWin(state, rng, events)
            val now = clock()
            PokeDoll.won(state, now)
            Catching.addToCollection(data, state, battle.wild, battle.tier, ball, now, events, special)
            state.ballCatches.merge(ball, 1, Int::plus)
            state.main?.let { main ->
                if (Tuning.CATCH_GIVES_XP) Progression.rewardCatch(data, state, main, battle.wild, now, rng, events)
                Healing.healMain(data, main, HealReason.CATCH, events) // after the rewards
            }
            // A ball catch is a win like the auto catch: defeat counters + trainer XP by tier.
            state.main?.let { it.defeats++ }
            state.defeats++
            state.catchWins++
            Trainer.addDefeatXp(state, battle.tier, events)
            Economy.onWin(state, events, bondLevel, rng)
        } else {
            state.main?.let { main ->
                val ab = SimpleView.of(data, battle, main).ability(true)
                if (ab == "ballfetch" && main.heldItem == null && battle.field.player.putIfAbsent("ab.ballfetch", 1) == null) {
                    Economy.give(state, ball)
                    events += GameEvent.Info("Ball Fetch returned the ${Items.name(ball)}!", main.uid)
                }
            }
            events += GameEvent.Info("${battle.wild.name} broke free!")   // the ball opens (its own animation and sound) ...
            events += GameEvent.Fled(battle.wild.name)                     // ... and the wild one runs away
        }
        if (special == "repeat-ball" && rng.nextInt(100) <
            if (success) Tuning.REPEAT_RETURN_CATCH_PERCENT else Tuning.REPEAT_RETURN_MISS_PERCENT) {
            Economy.give(state, special)
            events += GameEvent.Info("The Repeat Ball came back!")
        }
        state.battle = null
        events += ensureEncounter()
        StudyStats.record(state, events)
        Achievements.settle(data, state, clock(), events)
        return events
    }

